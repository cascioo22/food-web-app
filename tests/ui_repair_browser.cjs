/* Run npm install --prefix .qa --legacy-peer-deps playwright-core, then:
   node tests/ui_repair_browser.cjs
   Uses the existing Chrome CDP service; creates and cleans only its own fixtures. */
const { chromium } = require('../.qa/node_modules/playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.FOOD_UI_URL || 'http://host.docker.internal:3000';
const evidence = process.env.EVIDENCE_DIR || 'docs/evidence';
fs.mkdirSync(`${evidence}/screenshots`,{recursive:true});
(async () => {
  const browser = await chromium.connectOverCDP(process.env.CHROME_CDP || 'ws://hermes-chrome:3000/chrome');
  const initialWidth = Number(process.env.UI_WIDTH || 1280);
  const context = await browser.newContext({ viewport:{width:initialWidth,height:900} });
  const page = await context.newPage();
  page.setDefaultTimeout(8000);
  const errors=[], checks=[];
  page.on('pageerror', e=>errors.push(e.message));
  page.on('dialog', d=>d.accept());
  const name='UI QA '+Date.now();
  let rid, lid, pid;
  const api=async(path,method='GET',data)=>{
    const response=await context.request.fetch(base+path,{method,...(data===undefined?{}:{data})});
    const result=response.status()===204?null:await response.json();
    assert(response.ok(),JSON.stringify(result));return result;
  };
  const check=(label, condition=true)=>{assert(condition,label);checks.push(label);console.log('PASS '+label);};
  try {
    await page.goto(base);
    check('visible recipe creation control',await page.locator('#add-recipe-btn').isVisible()||await page.locator('#new-recipe-btn').isVisible());
    await page.locator('#new-recipe-btn').click();
    await page.locator('#import-url').click();
    check('input clicks do not close import',await page.locator('#import-modal').isVisible());
    if (process.env.FOOD_LIVE_IMPORT === '1') {
      await page.locator('#import-url').fill('https://www.bbcgoodfood.com/recipes/easy-pancakes');
      await page.locator('#url-import-form button[type=submit]').click();
      await page.waitForFunction(()=>document.querySelector('#manual-title').value==='Easy pancakes', null, {timeout:40000});
      check('live URL import populates review fields',(await page.locator('#manual-ingredients').inputValue()).split('\n').length===6);
      await page.locator('#close-import').click();
      await page.locator('#new-recipe-btn').click();
    }
    await page.locator('#manual-entry-btn').click();
    await page.locator('#manual-title').fill(name);
    await page.locator('#manual-ingredients').fill('2 cups flour\n1 egg');
    await page.locator('#manual-steps').fill('Mix the batter.\nBake and serve.');
    await page.locator('#manual-prep').fill('20 min');
    await page.locator('#manual-servings').fill('2');
    await page.locator('#manual-entry-form button[type=submit]').click();
    await page.locator('#import-modal').waitFor({state:'hidden'});
    rid=(await api('/recipes')).find(r=>r.title===name).id;
    check('manual recipe persists via UI');
    await page.locator(`.recipe-card[data-id="${rid}"] .recipe-title`).click();
    await page.locator('#ingredients-list li').first().waitFor();
    check('detail renders both ingredients and steps',(await page.locator('#ingredients-list li').count())===2&&(await page.locator('#steps-list li').count())===2);
    await page.locator('#select-ingredients-btn').click();
    await page.locator('#ingredient-picker-content input').first().check();
    await page.locator('#close-ingredient-picker').click();
    check('ingredient picker syncs detail selection',await page.locator('#ingredients-list input').first().isChecked());
    await page.locator('#edit-recipe-btn-footer').click();
    await page.locator('#edit-title').fill(name+' edited');
    // Deliberately delay read-only detail responses to catch editor clobbering over a real network.
    const detailRoute = /\/recipes\/\d+$/;
    await page.route(detailRoute,async route=>{const response=await route.fetch();await new Promise(resolve=>setTimeout(resolve,800));await route.fulfill({response});});
    await page.locator('#edit-recipe-form button[type=submit]').click();
    await page.locator('#edit-modal').waitFor({state:'hidden'});
    await page.waitForFunction(title=>document.querySelector('#modal-title').textContent===title,name+' edited');
    check('edit updates persisted title',(await api(`/recipes/${rid}`)).title===name+' edited');
    await page.locator('#edit-nutrition-btn').click();
    await page.locator('#nutrition-edit-modal details').first().locator('summary').click();
    await page.locator('#edit-calories-serv').fill('240');
    await page.waitForTimeout(1100); // Outlast the intentional delayed response above.
    check('nutrition input survives late recipe reads',(await page.locator('#edit-calories-serv').inputValue())==='240');
    await page.unroute(detailRoute);
    await page.locator('#save-nutrition-changes').click();
    await page.locator('#nutrition-edit-modal').waitFor({state:'hidden'});
    check('nutrition save persists',(await api(`/recipes/${rid}/nutrition`)).calories_per_serving===240);
    await page.locator('#close-modal').click();
    await page.getByRole('link',{name:'Lists',exact:true}).click();
    await page.waitForFunction(()=>typeof document.querySelector('#add-list-btn')?.onclick==='function');
    await page.locator('#add-list-btn').click();
    await page.locator('#list-name-input').fill(name);
    await page.locator('#save-list-btn').click();
    await page.locator('#add-item-btn').waitFor({state:'visible'});
    await page.waitForFunction(()=>!document.querySelector('#add-item-btn').disabled);
    lid=(await api('/grocery-lists')).find(l=>l.name===name).id;
    await page.locator('#add-item-btn').click();
    await page.locator('#edit-item-name-input').fill('Milk');
    await page.locator('.item-edit-form button[type=submit]').click();
    await page.locator('#item-edit-modal').waitFor({state:'hidden'});
    await page.locator('#items-list .item-check').check();
    await page.waitForFunction(()=>document.querySelector('#items-list .item-check')?.checked);
    await page.locator('#close-list-modal').click();
    await page.reload();
    await page.locator(`.list-card[data-id="${lid}"] .list-open`).click();
    check('list item completion survives reload',await page.locator('#items-list .item-check').isChecked());
    await page.locator('#items-list .item-text').click();
    await page.locator('#edit-item-name-input').fill('Oat milk');
    await page.locator('.item-edit-form button[type=submit]').click();
    await page.locator('#item-edit-modal').waitFor({state:'hidden'});
    check('item edit persisted',(await api(`/grocery-lists/${lid}`)).items[0].name==='Oat milk');
    await page.locator('#close-list-modal').click();
    await page.getByRole('link',{name:'Recipes',exact:true}).click();
    await page.locator(`.recipe-card[data-id="${rid}"] .recipe-title`).click();
    await page.locator('#ingredients-list input').first().check();
    await page.locator('#add-to-list').click();
    await page.locator(`[data-list-id="${lid}"]`).click();
    await page.getByRole('status').waitFor();
    check('bulk ingredient add persists',(await api(`/grocery-lists/${lid}`)).items.some(i=>i.name==='2 cups flour'));
    await page.locator('#close-ingredient-picker').click();
    check('closing child dialog retains recipe',await page.locator('#recipe-modal').isVisible());
    await page.locator('#add-photo-btn').click();
    const image=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a9qkAAAAASUVORK5CYII=','base64');
    await page.locator('#photo-file').setInputFiles({name:'qa.png',mimeType:'image/png',buffer:image});
    await page.locator('#photo-caption').fill(name);
    await page.locator('#upload-photo-form button[type=submit]').click();
    await page.locator('#upload-modal').waitFor({state:'hidden'});
    await page.locator('#gallery-grid img').first().waitFor();
    pid=(await api(`/recipes/${rid}/photos`))[0].id;
    check('recipe photo upload and linking persist');
    for(const width of [375,600,768,900,1280]){
      await page.setViewportSize({width,height:900});
      const geometry=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,modal:document.querySelector('#recipe-detail').getBoundingClientRect().toJSON()}));
      check(`recipe layout contains viewport at ${width}`,geometry.scroll<=geometry.width&&geometry.modal.x>=0&&geometry.modal.right<=geometry.width+1);
    }
    await page.setViewportSize({width:initialWidth,height:900});
    fs.mkdirSync(`${evidence}/screenshots`,{recursive:true});
    await page.screenshot({path:`${evidence}/screenshots/ui-repair-${initialWidth}.png`});
    await page.locator('#start-cooking-btn').click();
    await page.locator('#ingredients-container .ingredient-checkbox').first().waitFor();
    await page.locator('#ingredients-container .ingredient-checkbox').first().check();
    await page.locator('#steps-container .step-item').first().click();
    check('cooking retains original steps',await page.locator('#steps-container .step-item').count()===2);
    await page.reload();
    await page.locator('#ingredients-container .ingredient-checkbox').first().waitFor();
    check('cooking progress survives reload',await page.locator('#ingredients-container .ingredient-checkbox').first().isChecked()&&await page.locator('#steps-container .step-item').first().getAttribute('aria-pressed')==='true');
    await page.locator('#reset-progress-btn').click();
    check('cooking reset works',!(await page.locator('#ingredients-container .ingredient-checkbox').first().isChecked()));
    await page.locator('#back-btn').click();
    await page.getByRole('link',{name:'Photos',exact:true}).click();
    await page.locator(`.gallery-item[data-id="${pid}"]`).click();
    await page.locator('#caption-input').fill(name+' caption');
    await page.locator('#save-caption-btn').click();
    await page.locator('#photo-modal').waitFor({state:'hidden'});
    check('photo caption editing persists',(await api(`/photos/${pid}`)).caption===name+' caption');
    await page.locator(`.gallery-item[data-id="${pid}"]`).click();
    await page.locator('#unlink-recipe-btn').click();
    await page.locator('#photo-modal').waitFor({state:'hidden'});
    check('photo unlink persists',(await api(`/photos/${pid}`)).recipe_id===null);
    await page.locator(`.gallery-item[data-id="${pid}"]`).click();
    await page.locator('#delete-photo-btn').click();
    await page.locator('#photo-modal').waitFor({state:'hidden'});
    check('photo delete persists',!(await api('/photos')).photos.some(p=>p.id===pid));pid=null;
    await page.getByRole('link',{name:'Lists',exact:true}).click();
    await page.locator(`.list-card[data-id="${lid}"] .list-open`).click();
    await page.locator('#list-name-input').fill(name+' renamed');
    await page.locator('#save-list-btn').click();
    await page.waitForFunction(name=>[...document.querySelectorAll('.list-open h3')].some(e=>e.textContent===name),name+' renamed');
    check('list rename persists',(await api(`/grocery-lists/${lid}`)).name===name+' renamed');
    await page.locator('#items-list .item-delete').first().click();
    await page.waitForFunction(()=>document.querySelectorAll('#items-list .grocery-item').length===1);
    check('item deletion persists',(await api(`/grocery-lists/${lid}`)).items.length===1);
    await page.locator('#close-list-modal').click();
    await page.locator(`.list-card[data-id="${lid}"] [data-action=delete]`).click();
    await page.locator(`.list-card[data-id="${lid}"]`).waitFor({state:'hidden'});
    check('list deletion persists',!(await api('/grocery-lists')).some(l=>l.id===lid));lid=null;
    await page.getByRole('link',{name:'Recipes',exact:true}).click();
    await page.route('**/recipes',route=>route.fulfill({status:503,contentType:'application/json',body:'{"detail":"QA failure injection"}'}));
    await page.reload();await page.locator('#library-error').waitFor({state:'visible'});
    check('load failure displays retry');
    await page.unroute('**/recipes');await page.locator('#retry-recipes-btn').click();
    await page.locator(`.recipe-card[data-id="${rid}"]`).waitFor({state:'visible'});
    check('retry recovers real recipe data');
    await page.locator(`.recipe-card[data-id="${rid}"] [data-action=delete]`).click();
    await page.locator(`.recipe-card[data-id="${rid}"]`).waitFor({state:'hidden'});
    check('recipe deletion persists',!(await api('/recipes')).some(r=>r.id===rid));rid=null;
    check('no uncaught browser errors',errors.length===0);
  } finally {
    if(pid)await api(`/photos/${pid}`,'DELETE');
    if(rid)await api(`/recipes/${rid}`,'DELETE');
    if(lid)await api(`/grocery-lists/${lid}`,'DELETE');
    fs.writeFileSync(`${evidence}/ui-repair-browser-${initialWidth}.json`,JSON.stringify({base,checks,errors},null,2));
    await context.close();await browser.close();
  }
})().catch(e=>{console.error(e);process.exitCode=1;});
